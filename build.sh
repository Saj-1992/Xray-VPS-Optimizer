#!/usr/bin/env bash
# ============================================================================
# build.sh — compiles the modular src/ tree into dist/server-tools.sh.
# See docs/ARCHITECTURE.md. Never edit dist/ by hand.
# ============================================================================
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_DIR="${ROOT_DIR}/src"
OUT_FILE="${ROOT_DIR}/dist/server-tools.sh"
VERSION="$(tr -d '[:space:]' <"${ROOT_DIR}/VERSION")"

# Concatenation order is significant: header first, then core, modules,
# menu, and the entrypoint last. New src files must be added here.
SOURCES=(
  00-header.sh
  core/colors.sh
  core/log.sh
  core/ui.sh
  core/utils.sh
  core/state.sh
  core/backup.sh
  modules/detect.sh
  modules/sysinfo.sh
  modules/profile.sh
  modules/sysctl.sh
  modules/dns.sh
  modules/swap.sh
  modules/limits.sh
  modules/extras.sh
  modules/perf.sh
  modules/security.sh
  modules/vpn.sh
  modules/priority.sh
  modules/isp.sh
  modules/persist.sh
  modules/ipv6.sh
  modules/installer.sh
  modules/tools.sh
  modules/selfupdate.sh
  modules/optimize.sh
  modules/doctor.sh
  modules/health.sh
  menu.sh
  99-main.sh
)

# emit_isp_data — the Iran ISP address lists (data/isp) as a function, so the
# single built file works with no network and no second repository.
emit_isp_data() {
  local f id
  printf '\n# ------------------------- data/isp (embedded) -------------------------\n'
  printf '# _isp_embedded ID — the bundled address list of one ISP.\n'
  # The single quotes are deliberate: this text is generated shell code.
  # shellcheck disable=SC2016
  printf '_isp_embedded() {\n  case "$1" in\n'
  for f in "${ROOT_DIR}"/data/isp/*.ipv4; do
    id="$(basename "$f" .ipv4)"
    printf "    %s)\n      cat <<'ISP_DATA_EOF'\n" "$id"
    cat "$f"
    printf 'ISP_DATA_EOF\n      ;;\n'
  done
  printf '  esac\n}\n'
}

mkdir -p "${ROOT_DIR}/dist"

{
  printf '#!/usr/bin/env bash\n'
  printf '# =========================================================================\n'
  printf '# ServerTools v%s — single-file build\n' "$VERSION"
  printf '# Generated from src/ by build.sh — DO NOT EDIT THIS FILE DIRECTLY.\n'
  printf '# https://github.com/Saj-1992/Xray-VPS-Optimizer\n'
  printf '# =========================================================================\n'
  for src in "${SOURCES[@]}"; do
    if [[ $src == 99-main.sh ]]; then
      emit_isp_data
    fi
    printf '\n# ------------------------- src/%s -------------------------\n' "$src"
    # Strip per-file shebang/shellcheck directives; inject the version string.
    sed -e '\|^#!/usr/bin/env bash$|d' \
      -e '/^# shellcheck shell=bash$/d' \
      -e "s/@VERSION@/${VERSION}/g" \
      "${SRC_DIR}/${src}"
  done
} >"$OUT_FILE"

chmod +x "$OUT_FILE"
bash -n "$OUT_FILE"
printf 'Built %s (v%s, %s lines)\n' "$OUT_FILE" "$VERSION" "$(wc -l <"$OUT_FILE" | tr -d '[:space:]')"
