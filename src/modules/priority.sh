# shellcheck shell=bash
# ============================================================================
# modules/priority.sh — give VPN proxies the CPU and the OOM protection they
# deserve, for native services AND containers (Docker / Podman).
#
#   native services  systemd drop-in: Nice, OOMScoreAdjust, CPUWeight,
#                    LimitNOFILE — survives every restart and reboot.
#   containers       applied live to the container's host processes
#                    (renice every thread, oom_score_adj, cpu-shares), and
#                    re-applied at boot by a oneshot unit that exits at once.
#
# Nothing stays resident. A container that is recreated later (compose up,
# image update) starts without the boost until `st boost` or the next boot.
# ============================================================================

readonly ST_PRIO_NICE=-5
readonly ST_PRIO_OOM=-500
readonly ST_PRIO_CPU_WEIGHT=200  # systemd default is 100
readonly ST_PRIO_CPU_SHARES=2048 # docker default is 1024
readonly ST_PRIO_NOFILE=1048576
readonly ST_PRIO_UNIT='/etc/systemd/system/server-tools-boost.service'
readonly ST_PRIO_REGEX='marzban|marznode|pg[-_]?node|pasarguard|gozargah|x-?ui|xray|hiddify|sing-?box|hysteria|wireguard|wg-'
readonly -a ST_PRIO_SERVICES=(xray x-ui sing-box hysteria-server)

# Filled by priority_detect: service names, and "engine<TAB>name" lines.
ST_PRIO_SVC_TARGETS=()
ST_PRIO_CTR_TARGETS=()

# priority_detect — what is running right now that deserves priority.
priority_detect() {
  ST_PRIO_SVC_TARGETS=()
  ST_PRIO_CTR_TARGETS=()
  local svc engine line
  if has_cmd systemctl; then
    for svc in "${ST_PRIO_SERVICES[@]}"; do
      if systemctl is-active --quiet "$svc" 2>/dev/null; then
        ST_PRIO_SVC_TARGETS+=("$svc")
      fi
    done
  fi
  for engine in docker podman; do
    has_cmd "$engine" || continue
    # Match on name AND image, like detect_stack: a pg-node container is often
    # just called "node". grep exit 1 (no match) is a normal outcome.
    while IFS= read -r line; do
      [[ -n $line ]] && ST_PRIO_CTR_TARGETS+=("${engine}"$'\t'"${line}")
    done < <("$engine" ps --format '{{.Names}} {{.Image}}' 2>/dev/null |
      grep -iE "$ST_PRIO_REGEX" | awk '{print $1}' || true)
  done
  return 0
}

priority_has_targets() {
  priority_detect
  ((${#ST_PRIO_SVC_TARGETS[@]} + ${#ST_PRIO_CTR_TARGETS[@]} > 0))
}

# _prio_service_pids SERVICE — every process of the unit (its whole cgroup).
_prio_service_pids() {
  local svc="$1" cg main
  cg="$(systemctl show -p ControlGroup --value "$svc" 2>/dev/null)" || cg=''
  if [[ -n $cg && -r /sys/fs/cgroup${cg}/cgroup.procs ]]; then
    cat "/sys/fs/cgroup${cg}/cgroup.procs"
    return 0
  fi
  main="$(systemctl show -p MainPID --value "$svc" 2>/dev/null)" || main=''
  if [[ $main =~ ^[1-9][0-9]*$ ]]; then
    printf '%s\n' "$main"
  fi
  return 0
}

# _prio_container_pids ENGINE NAME — host PIDs of everything in the container.
_prio_container_pids() {
  "$1" top "$2" -eo pid 2>/dev/null | awk 'NR > 1 {print $1}'
}

# _prio_boost_pid PID — renice every thread (a Go proxy runs dozens; renice -p
# on the PID alone only touches the main thread) and shield it from the OOM
# killer. Returns 1 when the process could not be boosted at all.
_prio_boost_pid() {
  local pid="$1" tid ok=0
  [[ -d /proc/$pid ]] || return 1
  for tid in "/proc/${pid}/task/"*; do
    # A thread may exit between listing and renice; that is not a failure.
    if renice -n "$ST_PRIO_NICE" -p "${tid##*/}" >/dev/null 2>&1; then
      ok=1
    fi
  done
  ((ok)) || return 1
  printf '%s' "$ST_PRIO_OOM" >"/proc/${pid}/oom_score_adj" 2>>"$ST_LOG_FILE" ||
    log_warn "Could not lower oom_score_adj of PID ${pid}."
  return 0
}

# _prio_write_dropin SERVICE — persistent systemd settings for a native proxy.
# Returns 0 when the file changed, 1 when it was already correct.
_prio_write_dropin() {
  local svc="$1" dir file content
  dir="/etc/systemd/system/${svc}.service.d"
  file="${dir}/99-server-tools.conf"
  content="# Generated by ${ST_NAME} v${ST_VERSION}
[Service]
Nice=${ST_PRIO_NICE}
OOMScoreAdjust=${ST_PRIO_OOM}
CPUWeight=${ST_PRIO_CPU_WEIGHT}
LimitNOFILE=${ST_PRIO_NOFILE}"
  if [[ -f $file && "$(<"$file")" == "$content" ]]; then
    return 1
  fi
  st_track_file "$file"
  mkdir -p "$dir"
  printf '%s\n' "$content" >"$file"
}

# _prio_write_boot_unit — re-applies container priority after a reboot.
_prio_write_boot_unit() {
  if [[ ! -x $ST_INSTALL_PATH ]]; then
    log_warn "'st' is not installed (st --install) — container priority will not be re-applied at boot."
    return 3
  fi
  has_cmd systemctl || return 2
  st_track_file "$ST_PRIO_UNIT"
  cat >"$ST_PRIO_UNIT" <<EOF
# Generated by ${ST_NAME} v${ST_VERSION}
[Unit]
Description=ServerTools proxy priority (oneshot, exits after boot)
After=network-online.target docker.service podman.service
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
TimeoutStartSec=180
Environment=ST_BOOST_WAIT=90
ExecStart=${ST_INSTALL_PATH} boost

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload 2>>"$ST_LOG_FILE" || log_warn "daemon-reload failed."
  if systemctl enable server-tools-boost.service >/dev/null 2>>"$ST_LOG_FILE"; then
    manifest_add unit server-tools-boost.service
  else
    log_warn "Could not enable boot persistence for container priority."
    return 3
  fi
}

# priority_apply — boost everything detected. Prompts nothing.
# Returns 0 ok, 2 nothing to do, 3 partial.
priority_apply() {
  priority_detect
  if ((${#ST_PRIO_SVC_TARGETS[@]} + ${#ST_PRIO_CTR_TARGETS[@]} == 0)); then
    printf 'No proxy service or container found.\n'
    return 2
  fi

  local rc=0 svc entry engine name pid boosted reload=0
  for svc in "${ST_PRIO_SVC_TARGETS[@]}"; do
    if _prio_write_dropin "$svc"; then
      reload=1
    fi
    boosted=0
    while IFS= read -r pid; do
      [[ -n $pid ]] || continue
      if _prio_boost_pid "$pid"; then
        boosted=$((boosted + 1))
      fi
      # Raise the open-file ceiling of the running process too, so it does not
      # wait for a restart.
      if has_cmd prlimit; then
        prlimit --pid "$pid" --nofile="${ST_PRIO_NOFILE}:${ST_PRIO_NOFILE}" 2>>"$ST_LOG_FILE" ||
          log_warn "Could not raise nofile of PID ${pid} live (applies on next restart)."
      fi
    done < <(_prio_service_pids "$svc")
    if ((boosted > 0)); then
      printf '  %s  %s %s(%d processes, persisted via systemd)%s\n' \
        "$(ui_badge ok)" "$svc" "$C_MUTED" "$boosted" "$C_RESET"
    else
      printf '  %s  %s %s— drop-in written, running process not reachable%s\n' \
        "$(ui_badge warn)" "$svc" "$C_MUTED" "$C_RESET"
      rc=3
    fi
  done
  if ((reload)); then
    systemctl daemon-reload 2>>"$ST_LOG_FILE" || log_warn "daemon-reload failed."
  fi

  for entry in "${ST_PRIO_CTR_TARGETS[@]}"; do
    IFS=$'\t' read -r engine name <<<"$entry"
    boosted=0
    while IFS= read -r pid; do
      [[ -n $pid ]] || continue
      if _prio_boost_pid "$pid"; then
        boosted=$((boosted + 1))
      fi
    done < <(_prio_container_pids "$engine" "$name")
    "$engine" update --cpu-shares "$ST_PRIO_CPU_SHARES" "$name" >/dev/null 2>>"$ST_LOG_FILE" ||
      log_warn "Could not raise cpu-shares of ${name} (priority by nice still applies)."
    if ((boosted > 0)); then
      printf '  %s  %s %s(%s, %d processes)%s\n' \
        "$(ui_badge ok)" "$name" "$C_MUTED" "$engine" "$boosted" "$C_RESET"
    else
      printf '  %s  %s %s— no process could be boosted%s\n' \
        "$(ui_badge warn)" "$name" "$C_MUTED" "$C_RESET"
      rc=3
    fi
  done

  if ((${#ST_PRIO_CTR_TARGETS[@]} > 0)) && [[ ! -f $ST_PRIO_UNIT ]]; then
    _prio_write_boot_unit || rc=3
  fi
  log_info "Proxy priority applied (services=${#ST_PRIO_SVC_TARGETS[@]}, containers=${#ST_PRIO_CTR_TARGETS[@]}, rc=${rc})."
  return "$rc"
}

# priority_step — the non-interactive step used by Quick/Auto/Go.
priority_step() {
  # A temp file, not $(...): a subshell would hide st_track_file's bookkeeping
  # from this process, and st_run_step needs its status line to stay clean.
  local tmp out rc=0
  tmp="$(mktemp)"
  priority_apply >"$tmp" || rc=$?
  out="$(<"$tmp")"
  rm -f "$tmp"
  if [[ -n $out ]]; then
    ST_LOG_BUFFER+=("${out//$'\n'/; }")
  fi
  return "$rc"
}

# priority_boot — `st boost`: what the boot unit runs. Containers may still be
# starting, so it waits (ST_BOOST_WAIT seconds at most) for the first one.
priority_boot() {
  local waited=0 limit="${ST_BOOST_WAIT:-0}"
  while ((waited < limit)); do
    priority_detect
    if ((${#ST_PRIO_CTR_TARGETS[@]} > 0)); then
      break
    fi
    sleep 5
    waited=$((waited + 5))
  done
  priority_apply
}

# priority_menu — interactive screen with the explanation up front.
priority_menu() {
  ui_section "Proxy priority (native services + Docker/Podman)"
  priority_detect
  printf 'Under CPU pressure the proxy is the LAST thing that should slow down, and\n'
  printf 'the OOM killer should never pick it. This sets, per process:\n'
  printf '  · nice %s · OOM shield %s · CPU weight x2 · nofile %s\n' \
    "$ST_PRIO_NICE" "$ST_PRIO_OOM" "$ST_PRIO_NOFILE"
  printf 'Services get a systemd drop-in (permanent). Containers are boosted live\n'
  printf 'and again at every boot by a oneshot unit that exits immediately.\n\n'
  if ((${#ST_PRIO_SVC_TARGETS[@]} + ${#ST_PRIO_CTR_TARGETS[@]} == 0)); then
    printf 'No running proxy service or container was found.\n'
    return 0
  fi
  local entry
  for entry in "${ST_PRIO_SVC_TARGETS[@]}"; do
    printf '  · service   %s\n' "$entry"
  done
  for entry in "${ST_PRIO_CTR_TARGETS[@]}"; do
    printf '  · container %s\n' "${entry//$'\t'/ }"
  done
  ui_confirm_yes "Apply priority now? (no restart, no disconnects)" || return 0
  priority_apply || true # per-target outcome is printed above
}

# priority_verify — 0 in effect, 2 not set up, 3 drifted (Doctor contract).
priority_verify() {
  local svc file pid ni any=0
  for svc in "${ST_PRIO_SERVICES[@]}"; do
    file="/etc/systemd/system/${svc}.service.d/99-server-tools.conf"
    [[ -f $file ]] || continue
    systemctl is-active --quiet "$svc" 2>/dev/null || continue
    any=1
    pid="$(systemctl show -p MainPID --value "$svc" 2>/dev/null)" || pid=''
    [[ $pid =~ ^[1-9][0-9]*$ ]] || return 3
    ni="$(ps -o ni= -p "$pid" 2>/dev/null | tr -d '[:space:]')" || ni=''
    [[ $ni == "$ST_PRIO_NICE" ]] || return 3
  done
  if ((any)); then
    return 0
  fi
  if [[ -f $ST_PRIO_UNIT ]]; then
    return 0
  fi
  return 2
}
